/**
 * The generator contract.
 *
 * A generator is a pure function from an index to a question. Given the same
 * index it produces the same question forever, which is what makes the bank
 * reproducible: the seed script can be re-run, the import is keyed on a stable
 * `sourceKey`, and re-running it updates rows rather than duplicating them.
 *
 * Two rules hold everywhere and are worth stating before any of the maths:
 *
 *  1. THE ANSWER IS COMPUTED, NEVER TYPED. A generator picks parameters and
 *     then works the question out. `solve 3x + 7 = 22` is built by choosing
 *     x = 5, a = 3, b = 7 and computing c = 22 — so the answer cannot be wrong
 *     unless the arithmetic in this file is wrong, and that is tested.
 *  2. DISTRACTORS ARE REAL MISTAKES. A wrong option is generated by making a
 *     specific error a student actually makes — sign slip, forgetting to halve,
 *     dividing instead of multiplying — not by jittering the right answer.
 *     Random distractors are eliminable by inspection, which turns a maths
 *     question into a spot-the-odd-one-out question.
 *
 * `check` is the third rule, and the reason this can be trusted at 2,000
 * questions: a generator may supply an independent verification of its own
 * answer — substitute the root back into the equation, differentiate and
 * confirm the stationary point, re-derive the hypotenuse. The test harness runs
 * `check` over every variant of every generator, so a broken generator fails a
 * test rather than reaching a student.
 */

